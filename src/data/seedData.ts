export function calculatePriorityScore(
  recentUsageHours: number,
  purpose: BookingPurpose,
  reliabilityScore: number
): PriorityBreakdown {
  const baseFairness = 50;
  const recentUsagePenalty = 5 * recentUsageHours;
  const purposeWeight =
    purpose === 'Academic Research' || purpose === 'Capstone Project' || purpose === 'Safety-Critical Testing'
      ? 20
      : 5;
  const reliabilityBonus = reliabilityScore >= 95 ? 10 : 0;
  const rawScore = baseFairness - recentUsagePenalty + purposeWeight + reliabilityBonus;
  const totalScore = Math.max(5, Math.min(100, rawScore));

  const explanation = `Base Fairness (50) − Recent Usage Penalty (5 × ${recentUsageHours}h = ${recentUsagePenalty}) + Purpose Weight (${purpose}: +${purposeWeight}) + Reliability Bonus (+${reliabilityBonus}) = ${totalScore} pts`;

  return {
    baseFairness,
    recentUsageHours,
    recentUsagePenalty,
    purpose,
    purposeWeight,
    reliabilityBonus,
    totalScore,
    explanation,
  };
}

